"""Data-driven specification of the `oxide_parse` IR.

One table drives `validate_ir()`, the exported Draft 2020-12 JSON Schema (`ir.schema.json`, generated by
`scripts/gen_ir_schema.py`), and drift checks against Rust's `crates/core/src/ir.rs`.

Examples:
    >>> from oxide_parse import ir_spec
    >>> ir_spec.validate_structure({"object": {"title": {"pipe": [{"css": "h1"}, "text"]}}})
    []
"""
from __future__ import annotations

import json
from typing import Any, Dict, List, Tuple

# Field types: "str", "bool", "int", "uint", "posint", "float", "expr", "strlist", ("enum", (...)); trailing "?" allows null.
# Unit operations are encoded as plain strings in "pipe": "text", "first", ...
UNIT_OPS: Tuple[str, ...] = (
    "parent", "children", "root", "first", "last", "text", "own_texts", "main_content", "html", "inner_html", "index", "count", "exists",
    "required", "non_empty", "strip", "lower", "upper", "int", "float", "bool", "parse_json", "not",
)  # fmt: skip
# `{"name": <value>}` operations with a single scalar argument
STR_OPS: Tuple[str, ...] = ("css", "xpath", "key", "attr", "has_attr", "meta", "split", "join")
UINT_OPS: Tuple[str, ...] = ("at",)
EXPR_OPS: Tuple[str, ...] = ("map", "flat_map", "filter", "default", "eq", "ne", "contains", "starts_with", "ends_with", "and", "or", "parse_html")
EXPRLIST_OPS: Tuple[str, ...] = ("coalesce",)
# `{"name": {field: value, ...}}`: field -> (type, required)
STRUCT_OPS: Dict[str, Dict[str, Tuple[Any, bool]]] = {
    "slice": {"start": ("int?", False), "stop": ("int?", False)},
    "text_opts": {"sep": ("str", False), "strip": ("bool", False), "without": ("str?", False), "br": ("str?", False), "deep": ("bool?", False)},
    "table": {"mode": (("enum?", ("records", "grid", "split")), False), "strip": ("bool?", False), "header_sep": ("str?", False)},
    "markdown": {"without": ("str?", False)},
    "distill": {"keep": ("uint?", False), "max_text": ("uint?", False), "max_chars": ("uint?", False)},
    "adaptive": {"css": ("str", True), "key": ("str", True), "threshold": ("float?", False)},
    "map_opts": {"body": ("expr", True), "on_error": (("enum", ("raise", "null", "skip")), False)},
    "resolve_url": {"base": ("expr?", False)},
    "js_json": {"var": ("str?", False)},
    "sections": {"header": ("str", True), "items": ("str?", False)},
    "group_by": {"header": ("str", True), "items": ("str?", False)},
    "json_ld": {"schema_type": ("str?", False), "resolve_refs": ("bool?", False)},
    "microdata": {"schema_type": ("str?", False)},
    "next_flight": {"key": ("str?", False)},
    "meta_tags": {"prefixes": ("strlist", False), "values": (("enum?", ("auto", "first", "list")), False)},
    "replace": {"from": ("str", True), "to": ("str", True)},
    "regex": {"pattern": ("str", True), "group": ("uint", False)},
    "regex_all": {"pattern": ("str", True), "group": ("uint", False)},
    "if": {"cond": ("expr", True), "then": ("expr", True), "otherwise": ("expr", True)},
    "unique": {"by": ("expr?", False), "keep": (("enum?", ("first", "last")), False)},
    "parse_srcset": {"pick": (("enum?", ("max", "min")), False), "min_width": ("posint?", False), "min_density": ("float?", False)},
    "price": {"decimal": ("str?", False), "currency": ("str?", False)},
    "link_header": {"rel": ("str?", False)},
    "follow": {"request": ("expr", True), "meta": ("expr?", False), "schema": ("expr", True), "format": (("enum?", ("html", "json", "xml")), False)},
    "paginate": {"items": ("expr", True), "next": ("expr", True), "meta": ("expr?", False), "max_pages": ("posint?", False), "max_items": ("posint?", False), "unique_by": ("expr?", False), "keep": (("enum?", ("first", "last")), False)},
}  # fmt: skip

EXPR_KINDS: Tuple[str, ...] = ("pipe", "object", "list", "lit")


def all_op_names() -> List[str]:
    """Return a sorted list of all supported IR operation names.

    Returns:
        Sorted list combining unit, scalar, expression, and structured operation names.

    Examples:
        >>> from oxide_parse import ir_spec
        >>> "css" in ir_spec.all_op_names() and "paginate" in ir_spec.all_op_names()
        True
    """
    return sorted([*UNIT_OPS, *STR_OPS, *UINT_OPS, *EXPR_OPS, *EXPRLIST_OPS, *STRUCT_OPS])


def _kind(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "bool"
    if isinstance(v, int):
        return "int"
    if isinstance(v, float):
        return "float"
    if isinstance(v, str):
        return "str"
    if isinstance(v, list):
        return "list"
    if isinstance(v, dict):
        return "object"
    return type(v).__name__


def _check_scalar(v: Any, t: Any, path: str, out: List[str]) -> None:
    """Validate one field value against a table field type."""
    optional = False
    if isinstance(t, tuple):
        optional = t[0].endswith("?")
        base: Any = ("enum", t[1])
    else:
        optional = t.endswith("?")
        base = t[:-1] if optional else t
    if v is None:
        if not optional:
            out.append(f"{path}: must not be null")
        return
    if base == "expr":
        _expr(v, path, out)
    elif base == "str":
        if not isinstance(v, str):
            out.append(f"{path}: expected a string, got {_kind(v)}")
    elif base == "bool":
        if not isinstance(v, bool):
            out.append(f"{path}: expected true/false, got {_kind(v)}")
    elif base == "int":
        if not isinstance(v, int) or isinstance(v, bool):
            out.append(f"{path}: expected an integer, got {_kind(v)}")
    elif base == "uint":
        if not isinstance(v, int) or isinstance(v, bool) or v < 0:
            out.append(f"{path}: expected a non-negative integer, got {v!r}")
    elif base == "posint":
        if not isinstance(v, int) or isinstance(v, bool) or v < 1:
            out.append(f"{path}: expected a positive integer (>= 1), got {v!r}")
    elif base == "float":
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            out.append(f"{path}: expected a number, got {_kind(v)}")
    elif base == "strlist":
        if not isinstance(v, list) or not all(isinstance(x, str) for x in v):
            out.append(f"{path}: expected a list of strings")
    elif isinstance(base, tuple) and base[0] == "enum":
        if v not in base[1]:
            out.append(f"{path}: must be one of {list(base[1])}, got {v!r}")


def _op(op: Any, path: str, out: List[str]) -> None:
    if isinstance(op, str):
        if op in UNIT_OPS:
            return
        known = op in STR_OPS or op in UINT_OPS or op in EXPR_OPS or op in EXPRLIST_OPS or op in STRUCT_OPS
        hint = f" ({op!r} takes an argument: {{{op!r}: ...}})" if known else ""
        out.append(f"{path}: unknown operation {op!r}{hint}")
        return
    if not isinstance(op, dict) or len(op) != 1:
        out.append(f"{path}: an operation is a string or an object with exactly one key, got {_kind(op)}")
        return
    ((name, arg),) = op.items()
    here = f"{path}.{name}"
    if name in UNIT_OPS:
        if arg is not None:
            out.append(f"{here}: takes no argument (write {name!r})")
    elif name in STR_OPS:
        _check_scalar(arg, "str", here, out)
    elif name in UINT_OPS:
        _check_scalar(arg, "uint", here, out)
    elif name in EXPR_OPS:
        _expr(arg, here, out)
    elif name in EXPRLIST_OPS:
        if not isinstance(arg, list):
            out.append(f"{here}: expected a list of expressions, got {_kind(arg)}")
        else:
            for i, e in enumerate(arg):
                _expr(e, f"{here}[{i}]", out)
    elif name in STRUCT_OPS:
        spec = STRUCT_OPS[name]
        if not isinstance(arg, dict):
            out.append(f"{here}: expected an object with {sorted(spec)}, got {_kind(arg)}")
            return
        for field, (ftype, required) in spec.items():
            if field not in arg:
                if required:
                    out.append(f"{here}.{field}: missing (required)")
                continue
            _check_scalar(arg[field], ftype, f"{here}.{field}", out)
        for field in arg:
            if field not in spec:
                out.append(f"{here}.{field}: unknown field (known: {sorted(spec)})")
    else:
        out.append(f"{path}: unknown operation {name!r}")


def _expr(e: Any, path: str, out: List[str]) -> None:
    if not isinstance(e, dict) or len(e) != 1:
        out.append(f"{path}: an expression is an object with exactly one of {list(EXPR_KINDS)}, got {_kind(e)}")
        return
    ((kind, body),) = e.items()
    if kind == "pipe":
        if not isinstance(body, list):
            out.append(f"{path}.pipe: expected a list of operations, got {_kind(body)}")
            return
        for i, op in enumerate(body):
            _op(op, f"{path}[{i}]", out)
    elif kind == "object":
        if not isinstance(body, dict):
            out.append(f"{path}.object: expected an object of expressions, got {_kind(body)}")
            return
        for k, v in body.items():
            _expr(v, f"{path}.{k}", out)
    elif kind == "list":
        if not isinstance(body, list):
            out.append(f"{path}.list: expected a list of expressions, got {_kind(body)}")
            return
        for i, v in enumerate(body):
            _expr(v, f"{path}[{i}]", out)
    elif kind == "lit":
        try:
            json.dumps(body, allow_nan=False)
        except (TypeError, ValueError, RecursionError) as exc:
            out.append(f"{path}.lit: expected a JSON value ({exc})")
    else:
        out.append(f"{path}: unknown expression kind {kind!r} (use one of {list(EXPR_KINDS)})")


def validate_structure(ir: Any) -> List[str]:
    """Validate an IR dictionary recursively without short-circuiting on the first error.

    Args:
        ir: Decoded JSON-like IR value (typically from `to_ir()` or `json.loads()`).

    Returns:
        List of error messages formatted with `$.field[op]` paths, or `[]` when structurally valid. Never raises.

    Examples:
        >>> from oxide_parse import ir_spec
        >>> ir_spec.validate_structure({"object": {"a": {"pipe": ["bad_op"]}}})
        ["$.a[0]: unknown operation 'bad_op'"]
    """
    out: List[str] = []
    try:
        _expr(ir, "$", out)
    except RecursionError:
        out.append("$: IR is nested too deeply or contains a cycle")
    return out


# -- JSON Schema ------------------------------------------------------------------------------------------------------
def _schema_of(t: Any) -> Dict[str, Any]:
    if isinstance(t, tuple):
        base: Any = ("enum", t[1])
        optional = t[0].endswith("?")
    else:
        optional = t.endswith("?")
        base = t[:-1] if optional else t
    if base == "expr":
        s: Dict[str, Any] = {"$ref": "#/$defs/expr"}
    elif base == "str":
        s = {"type": "string"}
    elif base == "bool":
        s = {"type": "boolean"}
    elif base == "int":
        s = {"type": "integer"}
    elif base == "uint":
        s = {"type": "integer", "minimum": 0}
    elif base == "posint":
        s = {"type": "integer", "minimum": 1}
    elif base == "float":
        s = {"type": "number"}
    elif base == "strlist":
        s = {"type": "array", "items": {"type": "string"}}
    else:
        s = {"enum": list(base[1])}
    if optional:
        s = {"anyOf": [s, {"type": "null"}]}
    return s


def build_schema() -> Dict[str, Any]:
    """Build the Draft 2020-12 JSON Schema dictionary for the `oxide_parse` IR.

    Returns:
        JSON Schema dictionary describing valid `Expr` and `Op` objects.

    Examples:
        >>> from oxide_parse import ir_spec
        >>> schema = ir_spec.build_schema()
        >>> schema["title"]
        'oxide_parse IR'
    """
    ops: List[Dict[str, Any]] = [{"const": n} for n in UNIT_OPS]
    for n in STR_OPS:
        ops.append(_one(n, {"type": "string"}))
    for n in UINT_OPS:
        ops.append(_one(n, {"type": "integer", "minimum": 0}))
    for n in EXPR_OPS:
        ops.append(_one(n, {"$ref": "#/$defs/expr"}))
    for n in EXPRLIST_OPS:
        ops.append(_one(n, {"type": "array", "items": {"$ref": "#/$defs/expr"}}))
    for n, spec in STRUCT_OPS.items():
        props = {f: _schema_of(t) for f, (t, _r) in spec.items()}
        req = [f for f, (_t, r) in spec.items() if r]
        body: Dict[str, Any] = {"type": "object", "properties": props, "additionalProperties": False}
        if req:
            body["required"] = req
        ops.append(_one(n, body))
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://raw.githubusercontent.com/M-16gt/oxide_parse/main/python/oxide_parse/ir.schema.json",
        "title": "oxide_parse IR",
        "description": "An extraction schema as data: what `oxide_parse.to_ir(...)` produces and `compile(...)` accepts.",
        "$ref": "#/$defs/expr",
        "$defs": {
            "expr": {
                "oneOf": [
                    {"type": "object", "properties": {"pipe": {"type": "array", "items": {"$ref": "#/$defs/op"}}}, "required": ["pipe"], "additionalProperties": False},
                    {"type": "object", "properties": {"object": {"type": "object", "additionalProperties": {"$ref": "#/$defs/expr"}}}, "required": ["object"], "additionalProperties": False},
                    {"type": "object", "properties": {"list": {"type": "array", "items": {"$ref": "#/$defs/expr"}}}, "required": ["list"], "additionalProperties": False},
                    {"type": "object", "properties": {"lit": {}}, "required": ["lit"], "additionalProperties": False},
                ]
            },
            "op": {"oneOf": ops},
        },
    }  # fmt: skip


def _one(name: str, body: Dict[str, Any]) -> Dict[str, Any]:
    return {"type": "object", "properties": {name: body}, "required": [name], "additionalProperties": False}


def schema_json() -> str:
    """Render `build_schema()` formatted with trailing newline as committed in `ir.schema.json`.

    Returns:
        Pretty-printed JSON string encoding of the IR schema.

    Examples:
        >>> from oxide_parse import ir_spec
        >>> ir_spec.schema_json().lstrip().startswith("{")
        True
    """
    return json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"
