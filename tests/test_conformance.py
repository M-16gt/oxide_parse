def serial(value):
    if isinstance(value, float) and not math.isfinite(value):
        return {"nonfinite": str(value)}
    if isinstance(value, list):
        return [serial(v) for v in value]
    if isinstance(value, dict):
        return {k: serial(v) for k, v in value.items()}
    return value


@contextmanager
def observation(group: str, case_id: str, **inputs):
    row = {"group": group, "id": case_id, "input": inputs, "status": "ERROR"}
    ROWS.append(row)
    try:
        yield row
    except pytest.skip.Exception as exc:
        row.update(status="UNSUPPORTED", reason=str(exc))
        raise
    except pytest.xfail.Exception as exc:
        row.update(status="KNOWN_DIFFERENCE", reason=str(exc))
        raise
    except Exception as exc:
        if row["status"] != "FAIL":
            row.update(status="ERROR", error=f"{type(exc).__name__}: {exc}")
        raise


def compare(row: dict, expected, actual):
    row.update(expected=serial(expected), actual=serial(actual))
    # Compare canonical JSON bytes, including output ordering and scalar types.
    encode = lambda value: json.dumps(serial(value), ensure_ascii=True, sort_keys=True, separators=(",", ":")).encode()
    equal = encode(expected) == encode(actual)
    row["status"] = "PASS" if equal else "FAIL"
    key = f"{row['group']}/{row['id']}"
    if not equal and key in KNOWN_DIFFERENCES:
        pytest.xfail(KNOWN_DIFFERENCES[key])
    assert equal, f"{key}: expected {expected!r}, actual {actual!r}"


